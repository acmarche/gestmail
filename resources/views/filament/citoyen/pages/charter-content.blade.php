    <h2>Charte d'utilisation du service de messagerie citoyenne</h2>

    <p>En utilisant le service de messagerie citoyenne mis à disposition par la Ville de Marche-en-Famenne, vous acceptez les conditions suivantes :</p>

    <h3>1. Objet du service</h3>
    <p>Le service de messagerie citoyenne est mis à disposition des citoyens pour leurs communications personnelles. Il ne peut être utilisé à des fins commerciales, illégales ou contraires aux bonnes mœurs.</p>

    <h3>2. Responsabilités de l'utilisateur</h3>
    <ul>
        <li>Vous êtes responsable de la confidentialité de vos identifiants de connexion.</li>
        <li>Vous vous engagez à ne pas diffuser de contenus illicites, diffamatoires, ou portant atteinte aux droits d'autrui.</li>
        <li>Vous vous engagez à ne pas utiliser le service pour l'envoi massif de courriels non sollicités (spam).</li>
    </ul>

    <h3>3. Protection des données</h3>
    <p>Vos données personnelles sont traitées conformément au Règlement Général sur la Protection des Données (RGPD). Elles ne sont utilisées que dans le cadre de la gestion du service de messagerie.</p>

    <h3>4. Quota et limites</h3>
    <p>Un quota de stockage est attribué à chaque boîte mail. En cas de dépassement, la réception de nouveaux messages peut être bloquée.</p>

    <h3>5. Suspension du service</h3>
    <p>L'administrateur se réserve le droit de suspendre ou supprimer un compte en cas de non-respect de la présente charte.</p>
